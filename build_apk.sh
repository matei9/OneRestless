#!/bin/bash
set -e

# Override any of these from the environment, e.g.
#   ANDROID_SDK=$HOME/Android/Sdk ./build_apk.sh
PROJECT_DIR="${PROJECT_DIR:-$(cd "$(dirname "$0")" && pwd)}"
ANDROID_SDK="${ANDROID_SDK:-${ANDROID_HOME:-$HOME/Android/Sdk}}"
SDK_TOOLS="${SDK_TOOLS:-$ANDROID_SDK/build-tools/34.0.0}"
PLATFORM_JAR="${PLATFORM_JAR:-$ANDROID_SDK/platforms/android-34/android.jar}"
BUILD_DIR="${BUILD_DIR:-$PROJECT_DIR/build}"
OUT_APK="${OUT_APK:-$PROJECT_DIR/build/OneLineage.apk}"
[ -n "$JAVA_HOME" ] && export PATH="$JAVA_HOME/bin:$PATH"

# Tools default to the SDK binaries; each can be overridden (e.g. on Linux with a
# Windows SDK: AAPT2=<linux aapt2>, D8="java -cp .../lib/d8.jar com.android.tools.r8.D8",
# APKSIGNER="java -jar .../lib/apksigner.jar", ZIPALIGN="python3 tools/zipalign.py").
AAPT2="${AAPT2:-$SDK_TOOLS/aapt2}"
D8="${D8:-$SDK_TOOLS/d8}"
APKSIGNER="${APKSIGNER:-$SDK_TOOLS/apksigner}"
ZIPALIGN="${ZIPALIGN:-$SDK_TOOLS/zipalign -p 4}"

for f in "$PLATFORM_JAR"; do
    [ -e "$f" ] || { echo "missing: $f (set ANDROID_SDK / SDK_TOOLS / PLATFORM_JAR)"; exit 1; }
done

echo "=== 1. Cleaning & preparing build directories ==="
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR/gen" "$BUILD_DIR/classes" "$BUILD_DIR/dex"

cd "$PROJECT_DIR"

echo "=== 1b. Stamping version + build time ==="
VERSION_NAME=$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' AndroidManifest.xml | head -n1)
VERSION_CODE=$(sed -n 's/.*android:versionCode="\([^"]*\)".*/\1/p' AndroidManifest.xml | head -n1)
BUILD_TIME=$(TZ="${BUILD_TZ:-America/Chicago}" date '+%Y-%m-%d %H:%M %Z')
GIT_REV=$(git rev-parse --short HEAD 2>/dev/null || echo nogit)
git diff --quiet HEAD 2>/dev/null || GIT_REV="$GIT_REV+"
cat > res/values/build_info.xml <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- generated by build_apk.sh - do not edit -->
<resources>
    <string name="build_info" translatable="false">v$VERSION_NAME ($VERSION_CODE)\n$BUILD_TIME\n$GIT_REV${BUILD_TAG:+ $BUILD_TAG}</string>
</resources>
XML
echo "build_info: v$VERSION_NAME ($VERSION_CODE) $BUILD_TIME $GIT_REV"

# Optional local overlay (e.g. jars patched from a GSI whose license forbids
# redistribution): files in EXTRA_ASSETS_DIR replace same-named assets/ files
# in this build only, and never enter git.
ASSETS_SRC="$BUILD_DIR/assets"
mkdir -p "$ASSETS_SRC" && cp -r assets/. "$ASSETS_SRC"/

echo "=== 1c. Building svcstub.dex (placeholder binder services) ==="
mkdir -p "$BUILD_DIR/svcstub/classes" "$BUILD_DIR/svcstub/dex"
javac --release 8 -cp "$PLATFORM_JAR" -d "$BUILD_DIR/svcstub/classes" \
    svcstub/src/com/wewaffles/onelineage/stub/ServiceStub.java
$D8 --lib "$PLATFORM_JAR" --output "$BUILD_DIR/svcstub/dex" \
    "$BUILD_DIR/svcstub/classes/com/wewaffles/onelineage/stub"/*.class
cp "$BUILD_DIR/svcstub/dex/classes.dex" "$ASSETS_SRC/svcstub.dex"

KEYSTORE="$PROJECT_DIR/keystore/debug.keystore"
if [ ! -f "$KEYSTORE" ]; then
    mkdir -p "$PROJECT_DIR/keystore"
    keytool -genkey -v \
        -keystore "$KEYSTORE" \
        -storepass android \
        -alias androiddebugkey \
        -keypass android \
        -keyalg RSA \
        -keysize 2048 \
        -validity 10000 \
        -dname "CN=OneLineage,O=WeWaffles,C=US"
fi

echo "=== 1d. Building device overlays (overlay/*) ==="
# Each overlay/<Name> becomes assets/treble-overlay-<Name>.apk; master_prepare.sh
# installs the ones for the host device into the guest's /product/overlay.
for ov in overlay/*/; do
    name=$(basename "$ov")
    mkdir -p "$BUILD_DIR/overlay/$name"
    $AAPT2 compile --dir "$ov/res" -o "$BUILD_DIR/overlay/$name/res.zip"
    $AAPT2 link -I "$PLATFORM_JAR" --manifest "$ov/AndroidManifest.xml" \
        -o "$BUILD_DIR/overlay/$name/unsigned.apk" "$BUILD_DIR/overlay/$name/res.zip"
    $ZIPALIGN "$BUILD_DIR/overlay/$name/unsigned.apk" "$BUILD_DIR/overlay/$name/aligned.apk"
    $APKSIGNER sign --ks "$KEYSTORE" --ks-pass pass:android --ks-key-alias androiddebugkey \
        --key-pass pass:android --v4-signing-enabled false \
        --out "$ASSETS_SRC/treble-overlay-$name.apk" \
        "$BUILD_DIR/overlay/$name/aligned.apk"
    echo "overlay: treble-overlay-$name.apk"
done

if [ -n "$EXTRA_ASSETS_DIR" ]; then
    for f in "$EXTRA_ASSETS_DIR"/*; do
        case "$f" in *.txt|*.md) continue;; esac
        cp -f "$f" "$ASSETS_SRC"/ && echo "overlay asset: $(basename "$f")"
    done
fi

echo "=== 2. Compiling resources with aapt2 ==="
$AAPT2 compile --dir res -o "$BUILD_DIR/compiled_res.zip"

echo "=== 3. Linking resources with aapt2 ==="
$AAPT2 link \
    -I "$PLATFORM_JAR" \
    --manifest AndroidManifest.xml \
    -o "$BUILD_DIR/base.apk" \
    --java "$BUILD_DIR/gen" \
    "$BUILD_DIR/compiled_res.zip" \
    -A "$ASSETS_SRC"

echo "=== 4. Compiling Java sources ==="
javac --release 8 \
    -cp "$PLATFORM_JAR" \
    -d "$BUILD_DIR/classes" \
    src/com/wewaffles/onelineage/MainActivity.java \
    "$BUILD_DIR/gen/com/wewaffles/onelineage/R.java"

echo "=== 5. Generating Dalvik Executable (classes.dex) with d8 ==="
$D8 \
    --lib "$PLATFORM_JAR" \
    --output "$BUILD_DIR/dex" \
    "$BUILD_DIR/classes/com/wewaffles/onelineage"/*.class

echo "=== 6. Packaging classes.dex into APK ==="
cd "$BUILD_DIR/dex"
zip -u "$BUILD_DIR/base.apk" classes.dex
cd "$PROJECT_DIR"

echo "=== 7. Aligning APK with zipalign ==="
$ZIPALIGN "$BUILD_DIR/base.apk" "$BUILD_DIR/aligned.apk"

$APKSIGNER sign \
    --ks "$KEYSTORE" \
    --ks-pass pass:android \
    --ks-key-alias androiddebugkey \
    --key-pass pass:android \
    --out "$OUT_APK" \
    "$BUILD_DIR/aligned.apk"

echo "=== BUILD SUCCESSFUL ==="
echo "Output APK: $OUT_APK"
ls -la "$OUT_APK"
